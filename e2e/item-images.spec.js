import { test, expect } from "./fixture.js";
import { readFile } from "node:fs/promises";

const save = (page) => page.getByRole("button", { name: "Save", exact: true }).click();
const settings = (page) => page.getByRole("button", { name: "Settings for Spare keys", exact: true }).click();
const saved = (page) => page.evaluate(() => JSON.parse(localStorage.getItem("haven-inventory")));
const photo = { name: "keys.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1sAAAAASUVORK5CYII=", "base64") };

test("item presets persist through editing and moving, with uploads and backups", async ({ page }) => {
  await page.goto("/#room/living-room");
  await page.getByRole("button", { name: "Add item", exact: true }).first().click();
  await page.getByRole("textbox", { name: "Item name" }).fill("Spare keys");
  await expect(page.locator('.image-options input[type="radio"]')).toHaveCount(14);
  await page.getByRole("radio", { name: "Keys", exact: true }).check();
  await save(page);
  await expect(page.locator(".item-symbol .item-art")).toBeVisible();
  await page.reload();
  expect((await saved(page)).items[0].image).toBe("keys");
  await settings(page);
  await page.getByRole("radio", { name: "Book", exact: true }).check();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  expect((await saved(page)).items[0].image).toBe("keys");
  await settings(page);
  await page.getByLabel("Upload your own image").setInputFiles(photo);
  await expect(page.locator("[data-image-status]")).toContainText("Photo ready");
  await save(page);
  const image = (await saved(page)).items[0].image;
  expect(image).toMatch(/^data:image\/jpeg;base64,/);
  await page.getByRole("button", { name: "Add a container" }).click();
  await page.getByRole("textbox", { name: "Name", exact: true }).fill("Key drawer");
  await save(page);
  await settings(page);
  const drawer = (await saved(page)).locations.find(l => l.name === "Key drawer");
  await page.getByRole("combobox", { name: "Location", exact: true }).selectOption(drawer.id);
  await save(page);
  await page.getByRole("button", { name: /All items/ }).click();
  await page.reload();
  await expect(page.locator(".item-symbol img")).toBeVisible();
  expect((await saved(page)).items[0]).toMatchObject({ image, locationId: drawer.id });
  const downloading = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export a backup", exact: true }).click();
  const download = await downloading;
  const backup = JSON.parse(await readFile(await download.path(), "utf8"));
  expect(backup.inventory.items[0].image).toBe(image);
  await page.setViewportSize({ width: 320, height: 740 });
  await settings(page);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320);
  await expect(page.getByRole("radio", { name: "Your photo" })).toBeChecked();
  await page.getByLabel("Upload your own image").setInputFiles({ name: "bad.png", mimeType: "image/png", buffer: Buffer.from("bad") });
  await expect(page.locator("[data-image-status]")).toContainText("could not be read");
  await save(page);
  expect((await saved(page)).items[0].image).toBe(image);
  await settings(page);
  await page.getByRole("radio", { name: "Default", exact: true }).check();
  await save(page);
  await expect(page.locator(".item-symbol img, .item-symbol .item-art")).toHaveCount(0);
  expect((await saved(page)).items[0].image).toBeNull();
});

test("a photo can be uploaded while creating an item", async ({ page }) => {
  await page.goto("/#room/living-room");
  await page.getByRole("button", { name: "Add item", exact: true }).first().click();
  await page.getByRole("textbox", { name: "Item name" }).fill("Spare keys");
  await page.getByLabel("Upload your own image").setInputFiles(photo);
  await expect(page.locator("[data-image-status]")).toContainText("Photo ready");
  await save(page);
  await page.reload();
  await expect(page.locator(".item-symbol img")).toBeVisible();
});
